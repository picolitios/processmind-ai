import { expect, test } from '@playwright/test'
import { assertAccessible } from './assertAccessible'

test('acesso e navegação móvel funcionam com teclado e foco visível', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const email = page.getByLabel('E-mail')
  await email.focus()
  await expect(email).toBeFocused()
  expect(await email.evaluate(element => getComputedStyle(element).outlineStyle)).not.toBe('none')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Senha')).toBeFocused()
  await expect(page.getByRole('heading', { name: 'Bem-vindo de volta' })).toBeVisible()
  await assertAccessible(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)

  const unique = Date.now().toString(36)
  await page.getByRole('button', { name: 'Criar conta' }).click()
  await page.getByLabel('Seu nome').fill('Usuário E2E')
  await email.fill(`a11y-${unique}@example.com`)
  await page.getByLabel('Senha').fill('senha-acessivel-12345')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).last().click()
  await expect(page.getByRole('heading', { name: 'Organizações', exact: true })).toBeVisible()
  await page.getByLabel('Nome').fill(`Acessibilidade ${unique}`)
  await page.getByLabel('Identificador').fill(`a11y-${unique}`)
  await page.getByRole('button', { name: 'Criar organização' }).click()
  await expect(page.getByRole('heading', { name: 'Visão geral' })).toBeVisible()
  await assertAccessible(page)
  const imports = page.getByRole('link', { name: 'Importações' })
  await imports.focus()
  await expect(imports).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Importações' })).toBeVisible()
  await assertAccessible(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)

  await page.getByRole('button', { name: 'Ativar modo escuro' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await assertAccessible(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
